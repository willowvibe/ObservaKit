#!/usr/bin/env python3
"""Assemble the ObservaKit demo from the raw screen recording.

The raw capture is cut at the narration scene boundaries, padded by one
transition length at the end of every scene except the last, and joined with
FFmpeg ``xfade`` transitions. Padding each outgoing scene means the crossfade
overlaps a held frame instead of consuming timeline, so the final video keeps
the narration's exact duration.

No captions are burned in: the finished file carries the voice track only.

Inputs (generated by scripts/record_demo.py and the TTS step):
  video-work/observakit-raw.webm
  /tmp/observakit-tts/holds.json
  /tmp/observakit-tts/narration.wav

Outputs:
  observakit-demo.mp4
  observakit-demo-poster.jpg
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / "video-work"
TTS = Path("/tmp/observakit-tts")
DEFAULT_TRANSITION = 0.35


def run(command: list[str]) -> None:
    subprocess.run(command, check=True)


def ffmpeg(*args: str) -> None:
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args])


def probe_duration(path: Path) -> float:
    result = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=nw=1:nk=1",
            str(path),
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    return float(result.stdout.strip())


def cut_scene(raw: Path, start: float, duration: float, output: Path, pad: float) -> None:
    filters = [f"trim=duration={duration:.3f}", "setpts=PTS-STARTPTS"]
    if pad > 0:
        filters.append(f"tpad=stop_mode=clone:stop_duration={pad:.3f}")
    ffmpeg(
        "-ss",
        f"{start:.3f}",
        "-i",
        str(raw),
        "-t",
        f"{duration + pad:.3f}",
        "-vf",
        ",".join(filters),
        "-an",
        "-c:v",
        "libx264",
        "-preset",
        "veryfast",
        "-crf",
        "16",
        "-pix_fmt",
        "yuv420p",
        str(output),
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--transition", type=float, default=DEFAULT_TRANSITION)
    parser.add_argument("--poster-at", type=float, default=34.0)
    parser.add_argument("--output", type=Path, default=ROOT / "observakit-demo.mp4")
    parser.add_argument(
        "--poster", type=Path, default=ROOT / "observakit-demo-poster.jpg"
    )
    args = parser.parse_args()

    raw = WORK / "observakit-raw.webm"
    holds_path = TTS / "holds.json"
    narration = TTS / "narration.wav"
    for required in (raw, holds_path, narration):
        if not required.exists():
            raise SystemExit(f"missing input: {required}")

    timeline = json.loads(holds_path.read_text())
    holds = [float(value) for value in timeline["holds"]]
    starts = [float(value) for value in timeline["scene_starts"]]
    if len(holds) != len(starts):
        raise SystemExit("holds.json has mismatched holds and scene_starts")

    segments_dir = WORK / "segments"
    segments_dir.mkdir(exist_ok=True)
    for stale in segments_dir.glob("scene-*.mp4"):
        stale.unlink()

    segments: list[Path] = []
    last = len(holds) - 1
    for index, (start, hold) in enumerate(zip(starts, holds)):
        segment = segments_dir / f"scene-{index:02d}.mp4"
        cut_scene(raw, start, hold, segment, args.transition if index < last else 0.0)
        actual = probe_duration(segment)
        segments.append(segment)
        print(f"scene {index:02d}: {actual:.3f}s (planned {hold:.3f}s)", file=sys.stderr)

    # xfade offsets are based on the padded segment lengths. Each overlap
    # consumes one transition length, so the total returns to sum(holds).
    inputs: list[str] = []
    for segment in segments:
        inputs.extend(["-i", str(segment)])

    filters: list[str] = []
    label = "0:v"
    current = probe_duration(segments[0])
    for index in range(1, len(segments)):
        next_label = f"v{index}"
        offset = max(0.0, current - args.transition)
        filters.append(
            f"[{label}][{index}:v]xfade=transition=fade:"
            f"duration={args.transition:.3f}:offset={offset:.3f}[{next_label}]"
        )
        label = next_label
        current += probe_duration(segments[index]) - args.transition

    silent = WORK / "observakit-transitions.mp4"
    ffmpeg(
        *inputs,
        "-filter_complex",
        ";".join(filters),
        "-map",
        f"[{label}]",
        "-an",
        "-c:v",
        "libx264",
        "-preset",
        "slow",
        "-crf",
        "18",
        "-pix_fmt",
        "yuv420p",
        "-movflags",
        "+faststart",
        str(silent),
    )

    ffmpeg(
        "-i",
        str(silent),
        "-i",
        str(narration),
        "-map",
        "0:v:0",
        "-map",
        "1:a:0",
        "-c:v",
        "copy",
        "-c:a",
        "aac",
        "-b:a",
        "192k",
        "-shortest",
        "-movflags",
        "+faststart",
        str(args.output),
    )

    ffmpeg(
        "-ss",
        f"{args.poster_at:.3f}",
        "-i",
        str(args.output),
        "-frames:v",
        "1",
        "-q:v",
        "2",
        str(args.poster),
    )

    print(f"video:  {args.output} ({probe_duration(args.output):.3f}s)")
    print(f"poster: {args.poster}")


if __name__ == "__main__":
    main()
